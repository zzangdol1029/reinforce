"""
실습 #2 — 비선형 회귀 (TwoLayerNet + MLP)
==========================================
*밑바닥부터 시작하는 딥러닝 4* / Q-Network PDF 의 dezero4.py 와 동일한 코드입니다.

목표:
    입력 x ∈ [0, 1] 에 대해  y ≈ sin(2πx)  인 관계를 학습 데이터로부터 근사합니다.
    선형 모델(Wx+b)만으로는 sin 곡선을 표현할 수 없으므로,
    은닉층 + 비선형 활성화(sigmoid) 가 있는 2층 신경망을 사용합니다.

데이터:
    y_true = sin(2πx) + 균등 노이즈 U(0,1)  →  신경망이 노이즈까지 완벽히 맞추지는 못하고,
    평균적으로 진함 곡선을 따라가도록 학습됩니다.
"""

# -----------------------------------------------------------------------------
# 1) 라이브러리 임포트
# -----------------------------------------------------------------------------
import numpy as np
import matplotlib.pyplot as plt  # 학습 후 산점도 + 적합 곡선 시각화

from dezero import Model  # 신경망을 클래스로 정의할 때 상속하는 베이스 클래스
from dezero import optimizers  # 옵티마이저들이 들어 있는 모듈 (SGD, Adam 등)
import dezero.layers as L  # Linear 등 층(layer) 정의
import dezero.functions as F  # sigmoid, mean_squared_error 등 연산


# -----------------------------------------------------------------------------
# 2) 학습용 데이터셋 생성
# -----------------------------------------------------------------------------
# 재현 가능한 난수 시드 (같은 코드를 여러 번 돌려도 동일한 데이터)
np.random.seed(0)

# x: [0, 1) 구간에서 균등 분포로 100개 샘플, 형상 (100, 1)
#    마지막 차원이 1인 이유: Linear 층의 입력 차원과 행렬 곱 형태를 맞추기 위함
x = np.random.rand(100, 1)

# y: 진짜 관계는 sin(2πx) 이지만, 여기서는 측정 노이즈를 더해 '관측값'처럼 만듦
#    np.random.rand(100, 1) 은 [0, 1) 균등 노이즈 → 곡선 주변으로 점들이 퍼짐
y = np.sin(2 * np.pi * x) + np.random.rand(100, 1)

# -----------------------------------------------------------------------------
# 3) 하이퍼파라미터 (사람이 미리 정하는 값)
# -----------------------------------------------------------------------------
# 학습률(learning rate): 한 번의 역전파 뒤 가중치를 얼마나 크게 갱신할지
# 너무 크면 발산, 너무 작으면 수렴이 느림. 여기서는 0.2 가 슬라이드/교재 예제 값
lr = 0.2

# 반복 횟수: 전체 데이터에 대해 순전파·역전파·갱신을 몇 번 반복할지 (full-batch)
iters = 10000


# -----------------------------------------------------------------------------
# 4) 2층 신경망 모델 정의 (은닉층 1개 + 출력층)
# -----------------------------------------------------------------------------
class TwoLayerNet(Model):
    """
    구조 개요 (입력 차원 1 가정):

        x  -->  Linear(1 → hidden_size)  -->  sigmoid  -->  Linear(hidden_size → out_size)  -->  ŷ

    왜 비선형(sigmoid)이 필요한가?
        연속적인 Affine 변환만 반복하면 결국 또 하나의 Affine 과 동치입니다.
        중간에 비선형 활성화를 넣어야 '곡선' 같은 복잡한 함수를 근사할 수 있습니다
        (단층 퍼셉트론의 한계를 극복하는 전통적인 설명).

    DeZero 의 Model:
        - __init__ 에서 self.l1 = L.Linear(...) 처럼 층을 등록하면,
          자동으로 학습 가능한 매개변수가 모델에 묶입니다.
        - forward 는 순전파만 정의하면, loss.backward() 호출 시 역전파 그래프가 구축됩니다.
    """

    def __init__(self, hidden_size, out_size):
        # 부모 Model 초기화 (파라미터 등록 등 내부 처리)
        super().__init__()

        # 첫 번째 Affine(완전연결) 층: 입력 특성 수는 데이터에 맞게 자동 결정되지만,
        # 여기서는 x 가 (배치, 1) 이므로 실질적으로 입력 1차원 → hidden_size 차원으로 확장
        self.l1 = L.Linear(hidden_size)

        # 두 번째 Affine 층: 은닉 벡터(hidden_size) → 출력 차원(out_size)
        self.l2 = L.Linear(out_size)

    def forward(self, x):
        """
        순전파(forward pass).

        인자 x:
            형상 (배치 크기, 입력 차원). 여기서는 (100, 1) 또는 시각화용 (T, 1).

        반환:
            최종 출력 ŷ. 회귀 문제이므로 마지막에 별도 활성화 없이 선형 출력을 많이 둡니다
            (무제한 실수값을 내보낼 수 있음).
        """
        # 은닉층: 선형 변환 후 시그모이드로 [대략 0, 1] 근처로 눌러 줌
        # 시그모이드는 구불구불한 결정경계/비선형 매핑을 만들기 위한 하나의 선택지일 뿐이며,
        # ReLU, tanh 등 다른 활성화로 바꿀 수도 있습니다.
        y = F.sigmoid(self.l1(x))

        # 출력층: 은닉 표현을 다시 선형 결합하여 스칼라(또는 벡터) 예측값 생성
        y = self.l2(y)
        return y


# -----------------------------------------------------------------------------
# 5) 모델·옵티마이저 생성 및 연결
# -----------------------------------------------------------------------------
# 은닉 뉴런 수 10, 출력 차원 1 (각 x 에 대해 하나의 예측 실수)
model = TwoLayerNet(10, 1)

# SGD(Stochastic Gradient Descent): 각 파라미터의 gradient 에 학습률을 곱해 빼 줌
#   θ ← θ - lr * ∇θ L
optimizer = optimizers.SGD(lr)  # 옵티마이저 생성

# setup(model): 이 옵티마이저가 어떤 모델의 params() 를 갱신할지 등록
# 수동으로 for p in model.params(): p.data -= lr * p.grad 했던 것을 캡슐화한 것
optimizer.setup(model)  # 최적화할 모델을 옵티마이저에 등록


# -----------------------------------------------------------------------------
# 6) 학습 루프 (Full-batch 경사 하강법에 가까운 형태)
# -----------------------------------------------------------------------------
for i in range(iters):
    # --- (a) 순전파: 현재 가중치로 예측값 계산 ---
    # model(x) 는 내부적으로 forward(x) 를 호출합니다 (Model 클래스 편의 기능).
    y_pred = model(x)

    # --- (b) 손실: 평균 제곱 오차(MSE) ---
    # F.mean_squared_error(y, y_pred) 는 배치 전체에 대한 MSE 를 스칼라 Variable 로 반환합니다.
    # 회귀에서 널리 쓰이며, 이차 함수 형태라 미분이 매끄럽습니다.
    loss = F.mean_squared_error(y, y_pred)

    # --- (c) 이전 스텝에서 남아 있을 수 있는 기울기 초기화 ---
    # DeZero/PyTorch 계열에서 grad 는 보통 누적되므로, 매 스텝마다 비우는 습관이 중요합니다.
    model.cleargrads()

    # --- (d) 역전파: loss 에 연결된 계산 그래프를 따라 ∂loss/∂(각 파라미터) 계산 ---
    loss.backward()

    # --- (e) 파라미터 갱신: 옵티마이저가 등록된 모델의 grad 를 이용해 가중치 업데이트 ---
    optimizer.update()  # 옵티마이저로 매개변수 갱신

    # --- (f) 로깅: 1000 번마다 현재 손실 출력 (수렴 여부 확인용) ---
    if i % 1000 == 0:
        print(loss.data)


# -----------------------------------------------------------------------------
# 7) 결과 시각화 — 슬라이드 [그림 7-12] 와 같은 형태
# -----------------------------------------------------------------------------
# 학습에 썼던 100개 샘플을 산점도로 표시 (파란 점들)
plt.scatter(x, y, s=10)
plt.xlabel('x')
plt.ylabel('y')

# [0, 1] 구간을 0.01 간격으로 잘게 쪼개 연속적인 예측 곡선을 그리기 위한 입력 t
# [:, np.newaxis] 로 (N,) → (N, 1) 형상으로 바꿔 Linear 층과 행렬 곱 규격을 맞춤
t = np.arange(0, 1, .01)[:, np.newaxis]

# 학습이 끝난 model 로 구간 전체에 대한 예측 (곡선의 y 좌표)
y_pred = model(t)

# 빨간 선: 신경망이 학습한 함수 근사. 이상적으로는 검은 점선 sin(2πx) 근처를 따름
plt.plot(t, y_pred.data, color='r')

# 그래프 창 표시 (blocking). 창을 닫으면 프로그램 종료
plt.show()
